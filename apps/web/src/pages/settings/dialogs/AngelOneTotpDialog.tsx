import React from 'react';
import {
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  Typography,
  TextField,
  Button,
} from '@mui/material';
import KeyRounded from '@mui/icons-material/KeyRounded';

export interface AngelOneTotpDialogProps {
  open: boolean;
  onClose: () => void;
  clientCode: string;
  totp: string;
  onTotpChange: (val: string) => void;
  onSubmit: () => void;
  isPending: boolean;
}

export function AngelOneTotpDialog({
  open,
  onClose,
  clientCode,
  totp,
  onTotpChange,
  onSubmit,
  isPending,
}: AngelOneTotpDialogProps) {
  return (
    <Dialog
      open={open}
      onClose={onClose}
      maxWidth="xs"
      fullWidth
    >
      <DialogTitle sx={{ fontWeight: 700, display: 'flex', alignItems: 'center', gap: 1 }}>
        <KeyRounded sx={{ color: '#f59e0b' }} />
        Angel One TOTP Authorization
      </DialogTitle>
      <DialogContent sx={{ display: 'flex', flexDirection: 'column', gap: 2, pt: 1 }}>
        <Typography variant="body2" color="text.secondary">
          Enter the 6-digit TOTP code generated by your authenticator app for client code <strong>{clientCode || 'your account'}</strong>.
        </Typography>
        <TextField
          autoFocus
          label="6-Digit TOTP Code"
          value={totp}
          onChange={(e) => onTotpChange(e.target.value.replace(/\D/g, '').slice(0, 6))}
          placeholder="000000"
          fullWidth
          slotProps={{
            htmlInput: {
              inputMode: 'numeric',
              maxLength: 6,
              style: { textAlign: 'center', letterSpacing: '0.5em', fontSize: '1.25rem', fontWeight: 700 },
            },
          }}
        />
      </DialogContent>
      <DialogActions sx={{ px: 3, pb: 2.5 }}>
        <Button onClick={onClose} color="inherit">
          Cancel
        </Button>
        <Button
          variant="contained"
          color="warning"
          disabled={totp.length !== 6 || isPending}
          onClick={onSubmit}
          sx={{ fontWeight: 700 }}
        >
          {isPending ? 'Verifying...' : 'Authorize'}
        </Button>
      </DialogActions>
    </Dialog>
  );
}
